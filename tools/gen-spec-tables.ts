// Generates the numeric tables of docs/SPEC.md straight from the code, so every
// number in the spec is computed, not typed. Re-run after any tuning change:
//   deno run -A tools/gen-spec-tables.ts > docs/SPEC-tables.md
import { CLASSES, createStats, DAMAGE_SCALE, HEALTH_SCALE, FIGHT_LENGTH, powerIndex } from "../src/game/Stats.ts";
import { applyRaceBonus, RACES } from "../src/game/Races.ts";
import { bodyFromStats, density, physicsMultiplier, totalMass, toughness } from "../src/game/Physics.ts";
import { ALL_SKILLS } from "../src/game/Skills.ts";
import { PARAMS, type ArenaCategory } from "../src/game/ArenaConfig.ts";
import { adaptedRanges, NEUTRAL_ENV, SENSE_BASE, SENSE_FALLOFF } from "../src/game/Senses.ts";
import { STATUS_DEFS } from "../src/game/Status.ts";
import { luminosity } from "../src/graphics/Environment.ts";
import { stunDuration } from "../src/physics/SmashPhysics.ts";

const f = (n: number, d = 1) => n.toFixed(d);
const out: string[] = [];
const row = (...cells: (string | number | boolean)[]) => out.push(`| ${cells.map(String).join(" | ")} |`);

out.push("<!-- GENERATED by tools/gen-spec-tables.ts — do not edit by hand. -->", "");
out.push(`Scales: HEALTH_SCALE = ${HEALTH_SCALE}, FIGHT_LENGTH = ${FIGHT_LENGTH}, DAMAGE_SCALE = ${DAMAGE_SCALE}.`, "");

out.push("### T1. Class combat stats, body and physics (human, no subrace)", "");
row("Class", "STR", "VIT", "RES", "REF", "FOC", "INT", "HP", "Dmg/hit", "Interval s", "Armor", "Mass kg", "Density kg/m³", "Toughness", "Hits to kill a Warrior", "Stun/hit s");
row(...Array(16).fill("---"));
const warrior = applyRaceBonus(createStats("Warrior"), "human", null);
for (const c of CLASSES) {
  const s = applyRaceBonus(createStats(c), "human", null);
  const b = bodyFromStats(s);
  const vsW = s.attackPower * physicsMultiplier(b, bodyFromStats(warrior), 0);
  row(c, s.strength, s.vitality, s.resilience, s.reflex, s.focus, s.intelligence,
    Math.round(s.maxHealth), f(s.attackPower, 0), f(s.attackInterval, 3), f(s.armor, 2),
    f(totalMass(b)), f(density(b), 0), f(toughness(b), 0),
    f(warrior.maxHealth / vsW, 0), f(stunDuration(s.attackPower / DAMAGE_SCALE, 1.2, 0), 2));
}
out.push("");

out.push("### T2. Physics multiplier matrix (attacker row → defender column, at rest)", "");
row("atk \\ def", ...CLASSES);
row(...Array(CLASSES.length + 1).fill("---"));
for (const a of CLASSES) {
  const ab = bodyFromStats(createStats(a));
  row(a, ...CLASSES.map((d) => f(physicsMultiplier(ab, bodyFromStats(createStats(d)), 0), 3)));
}
out.push("");

out.push("### T3. Race deltas applied to a Warrior", "");
row("Race", "Subrace", "HP", "Dmg", "Interval", "Armor", "Mass kg");
row("---", "---", "---", "---", "---", "---", "---");
for (const r of RACES) for (const sub of [null, ...r.subspecies.map((x) => x.id)]) {
  const s = applyRaceBonus(createStats("Warrior"), r.id, sub);
  row(r.id, sub ?? "—", Math.round(s.maxHealth), f(s.attackPower, 0), f(s.attackInterval, 3), f(s.armor, 2), f(totalMass(bodyFromStats(s))));
}
out.push("");

out.push("### T4. Skills (24 = 8 classes × 3)", "");
row("Class", "Kind", "Name", "Element", "Dmg×", "Stun s", "Knock×", "Lifesteal", "Armor×", "Speed×", "Cooldown s", "Duration s", "Hit at");
row(...Array(13).fill("---"));
for (const s of ALL_SKILLS) {
  const p = s.payload;
  row(s.className, s.kind, s.name, s.element, f(p.damageMul, 2), f(p.stun, 2), f(p.knockbackMul, 2), f(p.lifesteal, 2), f(p.armorMul ?? 1, 2), f(p.speedMul ?? 1, 2), f(s.cooldown, 1), f(s.animation.duration, 2), f(s.animation.hitAt, 2));
}
out.push("");

out.push("### T5. Arena parameters by forge category", "");
for (const cat of ["space", "ground", "phases", "population", "items", "hazards", "atmosphere"] as ArenaCategory[]) {
  const list = PARAMS.filter((p) => p.category === cat);
  out.push(`**${cat}** (${list.length})`, "");
  row("Key", "Min", "Default", "Max", "Unit", "Meaning");
  row("---", "---", "---", "---", "---", "---");
  for (const p of list) row(`\`${p.key}\``, p.min, p.def, p.max, p.unit, p.note);
  out.push("");
}
out.push(`Total parameters: **${PARAMS.length}**.`, "");

out.push("### T6. Senses: base range, falloff, and adapted range by light level (no helmet, armour 0.5)", "");
row("Sense", "Base m", "Falloff exp", "Night (L=0.04)", "Dusk (L=0.35)", "Day (L=1.0)");
row("---", "---", "---", "---", "---", "---");
const at = (L: number) => adaptedRanges({ helmet: 0, armour: 0.5, race: {} }, { ...NEUTRAL_ENV, luminosity: L });
const night = at(0.04), dusk = at(0.35), day = at(1);
for (const k of ["sight", "hearing", "touch", "magnetism", "scent"] as const) {
  row(k, SENSE_BASE[k], SENSE_FALLOFF[k], f(night[k], 2), f(dusk[k], 2), f(day[k], 2));
}
out.push("");

out.push("### T7. Luminosity by sun elevation (cloud 0 / 0.5 / 1)", "");
row("Elevation °", "Clear", "Half cloud", "Overcast");
row("---", "---", "---", "---");
for (const deg of [-20, -6, 0, 5, 10, 15, 20, 45, 90]) {
  const r = (deg * Math.PI) / 180;
  row(deg, f(luminosity(r, 0), 3), f(luminosity(r, 0.5), 3), f(luminosity(r, 1), 3));
}
out.push("");

out.push("### T8. Status effects", "");
row("Status", "Disables", "Control", "Speed×", "Attack×", "DPS (base)", "Duration s", "Cleared by", "Good");
row(...Array(9).fill("---"));
for (const s of Object.values(STATUS_DEFS)) {
  row(s.name, s.disables, s.control, s.speedMul, s.attackMul, s.dps, s.duration, s.clearedBy.join(", ") || "—", s.good);
}
out.push("");

out.push("### T9. Balance index (DPS × effective HP) per class", "");
row("Class", "Power index", "Ratio to mean");
row("---", "---", "---");
const idx = CLASSES.map((c) => powerIndex(createStats(c)));
const mean = idx.reduce((a, b) => a + b, 0) / idx.length;
CLASSES.forEach((c, i) => row(c, f(idx[i], 0), f(idx[i] / mean, 3)));
out.push("");

console.log(out.join("\n"));
