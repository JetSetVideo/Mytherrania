// deno-lint-ignore-file no-explicit-any -- reads untyped summary JSON
// Writes docs/arena/VARIABLES.md: every input variable of a match (src/balance/Variables.ts) grouped
// by scope and category, which simulator reads it, which are dead, what the batch varies, the
// measured effect of each (from the latest vars batches, when present), and the open questions.
//   deno run -A tools/variables.ts
//   (first: deno run -A tools/batch.ts --design vars-extreme --matches 12000 --out artifacts/batch-vars
//           deno run -A tools/batch.ts --design vars-grid --matches 14000 --out artifacts/batch-vars-grid)
import { BATCH_VARIABLES, DEAD_ARENA_KEYS, valueAt, VARIABLE_BY_ID, VARIABLES, type VariableDef } from "../src/balance/Variables.ts";
import { varsGridCells, FIGHTER_AXES, ARENA_AXES } from "../src/balance/Gradient.ts";

const OUT = "docs/arena/VARIABLES.md";
const lines: string[] = [];
const p = (s = "") => lines.push(s);
const range = (v: VariableDef) => v.values ? `${v.values.length} values: ${v.values.slice(0, 6).join(", ")}${v.values.length > 6 ? ", …" : ""}` : `${v.min} … ${v.max}`;
const short = (s: string, n = 110) => (s.length > n ? s.slice(0, n - 1) + "…" : s).replace(/\|/g, "/");

async function readJson(path: string): Promise<any | null> {
  try { return JSON.parse(await Deno.readTextFile(path)); } catch { return null; }
}

const byScope = new Map<string, VariableDef[]>();
for (const v of VARIABLES) { const k = `${v.scope}`; if (!byScope.has(k)) byScope.set(k, []); byScope.get(k)!.push(v); }

p("# Every input variable of a match");
p();
p("Generated by `deno run -A tools/variables.ts` from `src/balance/Variables.ts` (built from ArenaConfig.PARAMS,");
p("the FighterSpec contract, Races / Stats / Archetypes / Birthsight, MatchRules, MatchControl / Disposition and");
p("ParameterBounds). INPUT variables only: what a match is set up with. What a match measures is FightTelemetry (wave M).");
p("`sim` = read by the headless simulator's pipeline (tests/variables_test.ts checks every flag against the sources).");
p();
p("| scope | variables | read by the headless sim | varied one by one by the batch |");
p("|---|---|---|---|");
for (const [scope, vs] of byScope) {
  const varied = vs.filter((v) => BATCH_VARIABLES.includes(v)).length;
  p(`| ${scope} | ${vs.length}${vs.some((v) => v.perSeat) ? " (× 2 seats)" : ""} | ${vs.filter((v) => v.sim).length} | ${varied} |`);
}
p(`| **total** | **${VARIABLES.length}** | **${VARIABLES.filter((v) => v.sim).length}** | **${BATCH_VARIABLES.length}** (${BATCH_VARIABLES.filter((v) => v.perSeat).length} per seat → ${BATCH_VARIABLES.length + BATCH_VARIABLES.filter((v) => v.perSeat).length} keys) |`);
p();
p(`Before wave J2 the batch varied **${FIGHTER_AXES.length + ARENA_AXES.length} knobs** (${[...FIGHTER_AXES, ...ARENA_AXES].join(", ")}): the six`);
p("attributes moved together as one \"stats\" knob, the birthsign was always none, the arena only changed size, wall ladder");
p("and prop count. Now `--design vars-extreme` sets every variable above independently to its min or max (enums: a");
p(`uniform value) and \`--design vars-grid\` steps each one alone (${varsGridCells()} cells per sweep).`);
p();

for (const [scope, vs] of byScope) {
  p(`## ${scope}`);
  p();
  const groups = new Map<string, VariableDef[]>();
  for (const v of vs) { if (!groups.has(v.group)) groups.set(v.group, []); groups.get(v.group)!.push(v); }
  for (const [g, gv] of groups) {
    p(`### ${scope} · ${g} (${gv.length})`);
    p();
    p("| id | kind | range | default | unit | sim | note |");
    p("|---|---|---|---|---|---|---|");
    for (const v of gv) {
      const dead = v.scope === "arena" && DEAD_ARENA_KEYS.has(v.id.slice(6));
      p(`| \`${v.id}\`${v.perSeat ? " ×2" : ""} | ${v.kind} | ${short(range(v), 60)} | ${v.def} | ${v.unit} | ${dead ? "**dead**" : v.sim ? "yes" : "no"} | ${short(v.note)} |`);
    }
    p();
  }
}

p("## Dead arena parameters (declared, read by nothing)");
p();
p(`${[...DEAD_ARENA_KEYS].map((k) => `\`${k}\``).join(", ")}. They appear in the forge`);
p("parameter list and in generated configs but no simulator, engine, physics, UI or graphics code reads them (source");
p("scan, re-checked by tests/variables_test.ts). Either wire them (gliders, sudden death, hazards, platforms, the rim");
p("lip and the senses count are each a feature that was planned) or delete them so the config stops promising them.");
p();

const ext = await readJson("artifacts/batch-vars/summary.json");
const grid = await readJson("artifacts/batch-vars-grid/summary.json");
if (ext?.effects) {
  p(`## Measured: each variable at its max vs its min (vars-extreme, ${ext.matches} matches, code ${String(ext.codeHash).slice(0, 12)})`);
  p();
  p("Everything else is randomised in both halves, so a difference is that variable's main effect. \"real\" = |z| over the");
  p("Bonferroni threshold for the number of variables tested (with ~70 keys, three or four would pass |z| ≥ 2 by chance).");
  p();
  p("| variable | Δ seat-A win (± se) | real? | Δ median duration | Δ ring-out share | Δ time-limit share |");
  p("|---|---|---|---|---|---|");
  for (const e of ext.effects.filter((e: any) => e.key.startsWith("A.")).concat(ext.effects.filter((e: any) => e.key.startsWith("arena.")).sort((a: any, b: any) => Math.abs(b.dRingout) - Math.abs(a.dRingout)).slice(0, 14))) {
    const pct = (v: number) => `${v >= 0 ? "+" : ""}${(v * 100).toFixed(1)} %`;
    p(`| \`${e.key}\` | ${pct(e.dWinA)} ± ${(e.se * 100).toFixed(1)} | ${e.significant ? "**yes**" : "noise"} | ${e.dDuration >= 0 ? "+" : ""}${e.dDuration.toFixed(1)} s | ${pct(e.dRingout)} | ${pct(e.dTime)} |`);
  }
  p();
  p("(Seat-B rows mirror seat A with the opposite sign; the arena rows are sorted by their effect on ring-outs, since an arena");
  p("variable should not favour a seat — and none does.)");
  p();
}
if (grid?.axes) {
  p(`## Measured: one variable stepped alone, everything else at its middle (vars-grid, ${grid.matches} matches)`);
  p();
  p("Seat A's win rate per step (n ≈ 48 per step, ±0.07):");
  p();
  for (const ax of ["A.fighter.level", "A.fighter.stat.strength", "A.fighter.stat.reflex", "A.fighter.stat.vitality", "A.fighter.stat.resilience", "A.fighter.stat.intelligence", "A.fighter.stat.focus", "A.fighter.gear", "A.fighter.aiLevel", "A.fighter.strategy", "A.fighter.race", "A.fighter.class"]) {
    const a = grid.axes[ax];
    if (!a) continue;
    const def = VARIABLE_BY_ID.get(ax.slice(2));
    const label = (k: string) => def?.values ? def.values[valueAt(def, Number(k)) - def.min] : k;
    p(`- \`${ax}\`: ${Object.entries(a).sort().map(([k, v]: [string, any]) => `${label(k)} → ${v.winA.mean.toFixed(2)}`).join(" · ")}`);
  }
  p();
}

p("## The questions this inventory was built to answer");
p();
const qa: [string, string][] = [
  ["Which variables exist?", "All of the tables above, built from the sources; adding a PARAMS key, a race, a class, an archetype or a birthsign adds it here automatically."],
  ["Which of them actually change a fight?", "The `sim` column for the headless batch. Twelve arena parameters change nothing anywhere (dead list). Of the six attributes, only strength and reflex move the headless win rate measurably; intelligence and focus are flat (mana is close to inert in the simulator: wave S found the same), vitality and resilience are weak."],
  ["What is the \"max\" of an attribute?", "Its per-stat cap (60 points), but a fighter can never spend more than its level budget (12 + 6 per level). The vars designs ask for 0 or 60 per attribute and scale the request down to the budget (`legalAllocation`), so \"strength at max\" on a level-1 fighter is the whole level-1 budget in strength — a legal build, not an impossible one."],
  ["What is the max of a race, a class, a weapon, a birthsign?", "There is none: enums take a uniform value in vars-extreme and every value in vars-grid."],
  ["Do both fighters get their own extremes?", "Yes: every fighter variable is drawn per seat, so max-vs-max, min-vs-min and every mix occur for every attribute independently."],
  ["What is the \"smallest ground\"?", "2 m in the headless batch (the contract's closet); the live engine clamps generated arenas to 34–120 m, so the engine never plays the closets. Stated, not fixed: the closet results are a headless-only regime."],
  ["Does each record tell the truth about its conditions?", "It did not for the clock: the record said timeLimit 90 / roamSeconds 6 (config defaults) while the simulator played a 6 s truce and a 180 s limit from MatchControl / Disposition. Fixed: the record now states the clock actually played (tested)."],
  ["Can the batch combine wall rules?", "It could not: the arena provider forced the second and third rule to −1. Fixed: the provider keeps the config's own rules (default −1, so the old designs are unchanged)."],
  ["Is an effect real or noise?", "Each effect carries its standard error, z and a Bonferroni flag; with 12 000 matches the arena variables' apparent 5–6 % effects on the win rate at 3 000 matches vanished (all noise), as they must on symmetric starts."],
  ["Does strategy make a fighter win, as the rules require?", "Only FULL strategy (edge play): against a middle opponent, none 0.60, basic 0.53, full 0.94. The basic decision tree is no better than walking in and swinging; it lengthens fights and adds ring-outs. Open: the tree needs work before \"no strategy loses\" holds for basic."],
  ["Are the classes balanced?", "No, in the headless simulator: against a middle opponent the casters lose (Mage 0.34, Necromancer 0.23, Priest 0.22) and the physical classes win (Archer 0.83, Warrior 0.76, Assassin 0.72, Rogue 0.64; Barbarian 0.51). It is the same cause as the flat intelligence/focus lines: the simulator's casting buys little (mana close to inert, wave S). Open: whether the live engine shows the same gap (the engine's casts have bars, pushback and powers the simulator does not model) — measure it with tools/probe-batch.ts runConditions before rebalancing."],
  ["What decides how a match ENDS?", "The arena: size (+68 s, −35 % ring-outs from min to max) and walls (+42 s, −24 % ring-outs, +9 % time-outs), then wall height, resistance, aspect and the curb height. Most rule parameters (towers, period, arc centre, symmetry, pit depth) have no measurable effect on the outcome."],
  ["Which variables are global constants, not match variables?", "The 68 ParameterBounds tunables (a balance edit) and the 7 MatchRules switches (compared as rule SETS by ablation, tools/batch.ts --rules)."],
];
for (const [q, a] of qa) { p(`**${q}** ${a}`); p(); }

await Deno.writeTextFile(OUT, lines.join("\n") + "\n");
console.log(`wrote ${OUT}: ${VARIABLES.length} variables, ${BATCH_VARIABLES.length} varied by the batch, ${DEAD_ARENA_KEYS.size} dead arena keys`);
