/** The studio's camera for a profile: the new pure framing when the tree exports it, else HEAD's #frameToRig law. */
async function portraitCamera(rig: ReturnType<typeof rigOf>, w: number, h: number): Promise<THREE.PerspectiveCamera> {
  const mod = await import(`file://${TREE}/src/graphics/PortraitStudio.ts`).catch(() => ({})) as any;
  if (typeof mod.portraitCamera === "function") return mod.portraitCamera(rig.group, w / h);
  // HEAD (wave P) law, copied: fov 30, yaw 0.35, pitch 0.05, distance (h/2 + 0.18)/tan(15 deg) in [0.9, 6], look at 0.55 h.
  const box = new THREE.Box3().setFromObject(rig.group), height = Math.max(0.5, box.max.y - box.min.y);
  const cam = new THREE.PerspectiveCamera(30, w / h, 0.05, 20), dist = Math.max(0.9, Math.min(6, (height / 2 + 0.18) / Math.tan((15 * Math.PI) / 180)));
  const horiz = Math.cos(0.05) * dist;
  cam.position.set(Math.sin(0.35) * horiz, 0.55 * height + Math.sin(0.05) * dist, Math.cos(0.35) * horiz);
  cam.lookAt(0, 0.55 * height, 0);
  cam.updateMatrixWorld(true);
  return cam;
}
