// deno-lint-ignore-file no-explicit-any -- QA probe.
import { chromium } from "playwright";
import { serveAsset } from "./serve.ts";
const server = Deno.serve({ hostname: "127.0.0.1", port: 8807, onListen() {} }, (r) => serveAsset(r));
const b = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true, args: ["--use-angle=metal", "--ignore-gpu-blocklist"] });
const page = await b.newPage({ viewport: { width: 1280, height: 1100 } });
await page.goto("http://127.0.0.1:8807/index.html", { waitUntil: "load" });
await page.waitForFunction(() => (globalThis as any).__MYTHERRANIA__, null, { timeout: 15000 });
await page.click('[data-action="start"]');
await page.waitForTimeout(400);
await page.evaluate(() => { ([...document.querySelectorAll(".race-card")].find((r) => (r as HTMLElement).dataset.race === "elf") as HTMLElement)?.click(); });
await page.waitForTimeout(200);
await page.evaluate(() => { (document.querySelector(".sign-chip") as HTMLElement)?.click(); });
await page.waitForTimeout(200);
const el = await page.$("#birthsign-preview .birthsign-preview");
await el?.scrollIntoViewIfNeeded();
await page.waitForTimeout(200);
await el?.screenshot({ path: "artifacts/qa-ui2/birthsign-preview.png" });
console.log("shot birthsign-preview.png");
await b.close(); server.shutdown();
