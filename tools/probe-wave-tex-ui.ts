/** In-page: a hash of the WebGL canvas drawn right after a render(0) (idle clock frozen by the caller). */
const canvasHash = () => {
  const pv = (globalThis as any).__MYTHERRANIA_PREVIEW__;
  const c = document.getElementById("creator-preview") as HTMLCanvasElement;
  pv.render(0);
  const o = document.createElement("canvas");
  o.width = c.width; o.height = c.height;
  const g = o.getContext("2d")!;
  g.drawImage(c, 0, 0);
  const d = g.getImageData(0, 0, o.width, o.height).data;
  let h = 2166136261 >>> 0, sum = 0;
  for (let i = 0; i < d.length; i += 4) { h = Math.imul(h ^ d[i], 16777619) >>> 0; h = Math.imul(h ^ d[i + 1], 16777619) >>> 0; h = Math.imul(h ^ d[i + 2], 16777619) >>> 0; sum += d[i] + d[i + 1] + d[i + 2]; }
  return { hash: h.toString(16), mean: Math.round((sum / (d.length / 4) / 3) * 10) / 10 };
};

/** In-page: scan the visible part of the canvas for skin hits (region + anchor), on a grid; only points where the canvas is the top element. */
const scanSkin = (step: number) => {
  const pv = (globalThis as any).__MYTHERRANIA_PREVIEW__;
  const c = document.getElementById("creator-preview") as HTMLCanvasElement;
  const r = c.getBoundingClientRect();
  const out: { x: number; y: number; region: string; anchor: number[] | null }[] = [];
  const top = Math.max(r.top + 4, 0), bottom = Math.min(r.bottom - 4, innerHeight), left = Math.max(r.left + 4, 0), right = Math.min(r.right - 4, innerWidth);
  for (let y = top; y < bottom; y += step) for (let x = left; x < right; x += step) {
    if (document.elementFromPoint(x, y) !== c) continue;
    const h = pv.debugPickSkin(x, y);
    if (h && h.region) out.push({ x: Math.round(x), y: Math.round(y), region: h.region, anchor: h.anchor });
  }
  return out;
};

/** The page audit inside the studio: overflow past the viewport, clipped text, tiny text, small targets, children outside. */
const auditStudio = () => {
  const vw = innerWidth;
  const root = document.getElementById("tex-studio")!;
  const visible = (e: Element) => { const r = e.getBoundingClientRect(), s = getComputedStyle(e); return r.width > 0 && r.height > 0 && s.visibility !== "hidden" && s.display !== "none" && Number(s.opacity) > 0.05; };
  const label = (e: Element) => { const h = e as HTMLElement; return `${e.tagName.toLowerCase()}${h.id ? "#" + h.id : ""}${h.classList.length ? "." + [...h.classList].slice(0, 2).join(".") : ""}`; };
  const overflow: string[] = [], clipped: string[] = [], tiny: string[] = [], small: string[] = [], outside: string[] = [];
  const rr = root.getBoundingClientRect();
  for (const e of root.querySelectorAll("*")) {
    if (!visible(e)) continue;
    const r = e.getBoundingClientRect();
    if (r.right > vw + 1 || r.left < -1) overflow.push(`${label(e)} [${Math.round(r.left)}..${Math.round(r.right)}]`);
    if (r.left < rr.left - 1 || r.right > rr.right + 1) outside.push(label(e));
    const h = e as HTMLElement, s = getComputedStyle(h);
    if (h.childElementCount === 0 && (h.textContent ?? "").trim().length > 1) {
      if (h.scrollWidth > h.clientWidth + 2 && s.overflow !== "visible" && h.clientWidth > 0) clipped.push(`${label(e)} "${h.textContent!.trim().slice(0, 30)}"`);
      if (parseFloat(s.fontSize) < 11) tiny.push(`${label(e)} ${s.fontSize}`);
    }
    const interactive = e.matches("button, summary, [role=radio], .stepper-arrow, label.tex-check");
    if (interactive && (r.width < 43.5 || r.height < 43.5)) small.push(`${label(e)} ${Math.round(r.width)}x${Math.round(r.height)}`);
  }
  // Mid-word breaks (skill pitfall 35): a word whose client rects span more than one line.
  const breaks: string[] = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const t = n.textContent ?? "", re = /\S+/g;
    let m: RegExpExecArray | null;
    while ((m = re.exec(t))) {
      const rg = document.createRange(); rg.setStart(n, m.index); rg.setEnd(n, m.index + m[0].length);
      const rects = [...rg.getClientRects()].filter((x) => x.width > 0);
      if (new Set(rects.map((x) => Math.round(x.top))).size > 1) breaks.push(m[0]);
    }
  }
  return { breaksN: breaks.length, breaks: breaks.slice(0, 5), overflowN: overflow.length, overflow: overflow.slice(0, 5), clippedN: clipped.length, clipped: clipped.slice(0, 5), tinyN: tiny.length, tiny: tiny.slice(0, 5), smallN: small.length, small: small.slice(0, 6), outsideN: outside.length, outside: outside.slice(0, 5), pageOverflowX: document.documentElement.scrollWidth > innerWidth + 1 };
};

/** Text contrast on the PIXELS (skill pitfall 25): hide the glyphs, screenshot the box, median colour vs the text colour. */
async function pixelContrast(page: Page, limit = 40) {
  const n: number = await page.evaluate((lim) => {
    const els = [...document.querySelectorAll<HTMLElement>("#tex-studio *")].filter((e) => {
      if (e.childElementCount > 0 || (e.textContent ?? "").trim().length < 2) return false;
      const r = e.getBoundingClientRect(), s = getComputedStyle(e);
      return r.width > 2 && r.height > 2 && s.visibility !== "hidden" && s.display !== "none" && !e.closest("option");
    });
    const kinds = new Map<string, HTMLElement[]>();
    for (const e of els) { const k = e.className || e.tagName; (kinds.get(k) ?? kinds.set(k, []).get(k)!).push(e); }
    const pick: HTMLElement[] = [];
    while (pick.length < lim && [...kinds.values()].some((l) => l.length)) for (const l of kinds.values()) { const e = l.shift(); if (e && pick.length < lim) pick.push(e); }
    document.querySelectorAll("[data-probe-tone]").forEach((e) => e.removeAttribute("data-probe-tone"));
    pick.forEach((e, i) => e.setAttribute("data-probe-tone", String(i)));
    return pick.length;
  }, limit);
  const rows: { kind: string; text: string; ratio: number }[] = [];
  for (let i = 0; i < n; i++) {
    const sel = `[data-probe-tone="${i}"]`;
    const info = await page.evaluate((sl) => {
      const e = document.querySelector(sl) as HTMLElement;
      e.scrollIntoView({ block: "center" });
      const r = e.getBoundingClientRect();
      const colour = getComputedStyle(e).color;
      // Hide only the GLYPHS: visibility:hidden would also hide the element's own background (a gold button).
      e.style.color = "transparent"; e.style.textShadow = "none";
      return { x: r.left, y: r.top, w: r.width, h: r.height, colour, kind: e.className || e.tagName, text: (e.textContent ?? "").trim().slice(0, 16), vw: innerWidth, vh: innerHeight };
    }, sel);
    if (info.w < 2 || info.h < 2 || info.y < 0 || info.y + info.h > info.vh) { await page.evaluate((sl) => { const e = document.querySelector(sl) as HTMLElement; e.style.color = ""; e.style.textShadow = ""; }, sel); continue; }
    const png = await page.screenshot({ clip: { x: Math.max(0, info.x), y: info.y, width: Math.min(info.w, info.vw - info.x), height: info.h } });
    const res = await page.evaluate(async ([sl, data, colour]) => {
      { const e = document.querySelector(sl) as HTMLElement; e.style.color = ""; e.style.textShadow = ""; }
      const img = new Image(); img.src = `data:image/png;base64,${data}`; await img.decode();
      const cv = document.createElement("canvas"); cv.width = img.width; cv.height = img.height;
      const g = cv.getContext("2d")!; g.drawImage(img, 0, 0);
      const d = g.getImageData(0, 0, cv.width, cv.height).data;
      const lin = (x: number) => { x /= 255; return x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4; };
      const lums: number[] = [];
      for (let k = 0; k < d.length; k += 4) lums.push(0.2126 * lin(d[k]) + 0.7152 * lin(d[k + 1]) + 0.0722 * lin(d[k + 2]));
      lums.sort((a, b) => a - b);
      const lb = lums[lums.length >> 1];
      const m = /([\d.]+)[ ,]+([\d.]+)[ ,]+([\d.]+)/.exec(colour)!;
      const lt = 0.2126 * lin(+m[1]) + 0.7152 * lin(+m[2]) + 0.0722 * lin(+m[3]);
      return (Math.max(lt, lb) + 0.05) / (Math.min(lt, lb) + 0.05);
    }, [sel, encodeBase64(new Uint8Array(png)), info.colour] as const);
    rows.push({ kind: info.kind, text: info.text, ratio: +res.toFixed(2) });
  }
  const sorted = rows.slice().sort((a, b) => a.ratio - b.ratio);
  return { sampled: rows.length, min: sorted[0]?.ratio ?? null, below45: rows.filter((r) => r.ratio < 4.5).length, worst: sorted.slice(0, 4) };
}

