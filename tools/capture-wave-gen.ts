    if (stageId === "final") previewStage.draw(renderer as any, scene, cam); else renderer.render(scene, cam);
    const px = readTile();
    const m = measure(px, ax.mirror, (TW - 1) / 2); // pixel centres: column x mirrors to TW - 1 - x
    const col = i % 3, row = Math.floor(i / 3);
    const ox = col * TW, oy = HEAD + row * (TH + LAB);
    ctx.drawImage(renderer.domElement, ox, oy + LAB);
    ctx.strokeStyle = "#444"; ctx.strokeRect(ox + 0.5, oy + LAB + 0.5, TW - 1, TH - 1);
    ctx.fillStyle = "#d8c9a8"; ctx.font = (14 * S) + "px sans-serif";
    const meas = ax.mirror ? "  sym " + m.mirrorIoU + "  cΔ " + m.mirrorColourDiff : "";
    ctx.fillText(ax.label + "  comps " + m.components + meas, ox + 6 * S, oy + 16 * S);
