/** Numbers behind the skeleton sheets: L/R mirror deviation of every paired joint (bind and T-pose) and arm slope. */
function skeletonCheck(s: any): any {
  const bones: any[] = s.skeleton?.bones ?? s.plan?.bones ?? [];
  const bind: Record<string, number[]> = Object.fromEntries(bones.map((b) => [b.id, b.head]));
  const tp: Record<string, number[]> = s.skeleton?.tPose ?? {};
  const mirror = (P: Record<string, number[]>) => {
    let worst = 0, pair = "";
    for (const id of Object.keys(P)) {
      if (!id.endsWith("L")) continue;
      const r = P[id.slice(0, -1) + "R"]; if (!r) continue;
      const l = P[id], d = Math.hypot(l[0] + r[0], l[1] - r[1], l[2] - r[2]) * 1000;
      if (d > worst) { worst = d; pair = id.slice(0, -1); }
    }
    return { maxMm: +worst.toFixed(2), pair };
  };
  const slope = (side: string) => {
    const a = tp["shoulder" + side], b = tp["wrist" + side] ?? tp["hand" + side] ?? tp["elbow" + side];
    if (!a || !b) return null;
    return +(Math.atan2(b[1] - a[1], Math.hypot(b[0] - a[0], b[2] - a[2])) * 180 / Math.PI).toFixed(2);
  };
  return { bones: bones.length, disks: (s.skeleton?.disks ?? []).length, bindMirror: mirror(bind), tPoseMirror: mirror(tp), tPoseArmSlopeDeg: { L: slope("L"), R: slope("R") }, tPoseKeys: Object.keys(tp).length };
}

