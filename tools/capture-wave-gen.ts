  obj.updateMatrixWorld(true);
  const { c, hy } = cur.frame;
  const hx = hy * TW / TH;
  const out = document.createElement("canvas");
  out.width = TW * 3; out.height = HEAD + 2 * (TH + LAB);
  const ctx = out.getContext("2d")!;
  ctx.fillStyle = "#15171c"; ctx.fillRect(0, 0, out.width, out.height);
  ctx.fillStyle = "#f0e6d0"; ctx.font = "bold " + (18 * S) + "px sans-serif"; ctx.fillText(title, 10 * S, 23 * S);
