    persp.near = Math.max(0.1, dist - 4); persp.far = dist + 4; persp.updateProjectionMatrix();
    cam.position.copy(centre).addScaledVector(dir, dist);
    cam.up.copy(up); cam.lookAt(centre); cam.updateMatrixWorld(true);
    const right = new THREE.Vector3().crossVectors(up, dir).normalize().negate();
    const L = dir.clone().addScaledVector(up, 0.45).addScaledVector(right, 0.3).normalize();
    key.position.copy(centre).addScaledVector(L, 5); key.target.position.copy(centre); key.target.updateMatrixWorld();
