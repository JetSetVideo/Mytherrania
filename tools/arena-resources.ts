// Wave J (lane J-B): resource / health tables BEFORE and AFTER the Wave J race-physiology change,
// generated from the code (the "before" column replays the legacy formulas: mana regen 3 /s and
// stamina regen 5 /s flat, health = the class + race deltas clamped to 30–60 k with no race factor).
//
//   deno run -A tools/arena-resources.ts [--out artifacts/batch/resources.md]

import { RACES, applyRaceBonus, raceAffinity } from "../src/game/Races.ts";
import { applySecondary } from "../src/game/SecondaryStats.ts";
import { CLASSES, createStats, type ClassName } from "../src/game/Stats.ts";
import { createResources, LEGACY_MANA_REGEN } from "../src/game/Resources.ts";

const LEGACY_STAMINA_REGEN = 5;

function arg(name: string, dflt: string): string {
  const i = Deno.args.indexOf(`--${name}`);
  return i >= 0 && i + 1 < Deno.args.length ? Deno.args[i + 1] : dflt;
}

interface Row { manaB: number; manaA: number; refillB: number; refillA: number; stamB: number; stamA: number; hpB: number; hpA: number }

function row(cls: ClassName, race: string, subrace: string | null): Row {
  const after = applySecondary(applyRaceBonus(createStats(cls), race, subrace), subrace, null);
  const res = createResources(after, { race, subrace });
  // Legacy health: undo the race factor inside the same clamp window (the factor is the only change).
  const k = raceAffinity(race, subrace).health;
  const rawAfter = applyRaceBonus(createStats(cls), race, subrace).maxHealth;
  const unclamped = rawAfter > 30000 && rawAfter < 60000 ? rawAfter / k : legacyHealth(cls, race, subrace);
  const hpB = Math.max(30000, Math.min(60000, unclamped));
  return {
    manaB: LEGACY_MANA_REGEN, manaA: res.mana.regenPerSecond,
    refillB: res.mana.max / LEGACY_MANA_REGEN, refillA: res.mana.max / res.mana.regenPerSecond,
    stamB: LEGACY_STAMINA_REGEN, stamA: res.stamina.regenPerSecond,
    hpB, hpA: after.maxHealth,
  };
}

/** Pre-Wave-J applyRaceBonus health, recomputed from the deltas (used when the clamp binds). */
function legacyHealth(cls: ClassName, race: string, subrace: string | null): number {
  const r = RACES.find((x) => x.id === race)!;
  const b: Record<string, number> = { ...r.mods };
  const tw = r.subspecies.find((s) => s.id === subrace)?.tweak ?? {};
  for (const [kk, v] of Object.entries(tw)) b[kk] = (b[kk] ?? 0) + (v ?? 0);
  return createStats(cls).maxHealth + ((b.vitality ?? 0) * 2 + Math.floor((b.strength ?? 0) / 2)) * 1000;
}

const mean = (rows: Row[], k: keyof Row) => rows.reduce((t, r) => t + r[k], 0) / rows.length;
const f = (v: number, d = 2) => v.toFixed(d);
const L: string[] = [];
L.push("# Resource and health tables — before / after Wave J (generated by tools/arena-resources.ts)", "");
L.push("Race rows: the mean over the race's three sub-races, class Warrior, level 1, no gear. Before: mana 3 /s and stamina 5 /s for everyone, health without the race constitution factor.", "");
L.push("| race | mana regen /s before → after | mana refill from empty s before → after | stamina regen /s before → after | max health before → after |", "|---|---|---|---|---|");
const byRace: Record<string, Row> = {};
for (const r of RACES) {
  const rows = r.subspecies.map((s) => row("Warrior", r.id, s.id));
  const m: Row = { manaB: mean(rows, "manaB"), manaA: mean(rows, "manaA"), refillB: mean(rows, "refillB"), refillA: mean(rows, "refillA"), stamB: mean(rows, "stamB"), stamA: mean(rows, "stamA"), hpB: mean(rows, "hpB"), hpA: mean(rows, "hpA") };
  byRace[r.id] = m;
  L.push(`| ${r.id} | ${f(m.manaB)} → **${f(m.manaA)}** | ${f(m.refillB, 0)} → **${f(m.refillA, 0)}** | ${f(m.stamB)} → **${f(m.stamA)}** | ${f(m.hpB, 0)} → **${f(m.hpA, 0)}** |`);
}
const order = (k: keyof Row) => Object.entries(byRace).sort((a, b) => b[1][k] - a[1][k]).map(([id]) => id).join(" > ");
L.push("", `Orders after: mana regen ${order("manaA")} · stamina regen ${order("stamA")} · health ${order("hpA")}.`);
L.push(`Orders before: mana regen all equal · stamina regen all equal · health ${order("hpB")}.`, "");
L.push("Class rows: a human of each class (no sub-race), level 1, no gear.", "");
L.push("| class | mana max | mana regen /s before → after | refill s before → after | stamina regen /s before → after |", "|---|---|---|---|---|");
for (const c of CLASSES) {
  const r = row(c, "human", null);
  const max = r.refillA * r.manaA;
  L.push(`| ${c} | ${f(max, 0)} | ${f(r.manaB)} → **${f(r.manaA)}** | ${f(r.refillB, 0)} → **${f(r.refillA, 0)}** | ${f(r.stamB)} → **${f(r.stamA)}** |`);
}
const md = L.join("\n") + "\n";
const out = arg("out", "");
if (out) await Deno.writeTextFile(out, md);
console.log(md);
