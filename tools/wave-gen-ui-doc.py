w("  so no inverse of `proportionsFor` is needed. The Creator's height/weight/silhouette steppers take these bands as their min/max.")
w("- **0..1000 stat view** (`src/ui/StatView.ts`, beside the viewer above the sheet): Strength, Agility, Intelligence, Level from")
