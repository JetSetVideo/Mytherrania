// ── toe-out ──
const GEOM = legacyLegGeometryFor("human", null, 1.75, 75);
const LIM = limitTableFrom(defaultHumanoid().limits());
function toe(segs: ScenarioSegment[], on: boolean) {
  const an = new Animator(GEOM, LIM), st = motionStyleFor({ race: "human", seed: 3 });
  st.setLiveImmediate({ hpFrac: 1, staminaFrac: 1, manaFrac: 1, exhausted: false });
  an.setStyle(st);
  if (!on) an.output.toeOut.fill(0);
  const fk = newLegFK3(), acc = [0, 0];
  let n = 0;
  const res = runScenario(an, segs, {
    hz: 60, accel: 54, holdFacing: true,
    onFrame: (t, out) => {
      if (t < 1) return;
      n++;
      for (let i = 0 as Side; i < 2; i = (i + 1) as Side) {
        legFK3(GEOM, out.angles, i, out.hipRoll[i], out.ankleRoll[i], fk, out.toeOut[i]);
        acc[i] += measuredToeOut(GEOM.hipLateral[i], fk.heel, fk.toe) * 180 / Math.PI;
      }
    },
  });
  return { L: acc[0] / n, R: acc[1] / n, slide: Math.max(0, ...res.drift) * 1000 };
}

